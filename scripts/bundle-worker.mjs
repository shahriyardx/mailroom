/**
 * Bundles the Cloudflare email worker into a single ES module and writes it
 * into the app as a string, so the dashboard can upload it through the
 * Cloudflare API without wrangler or a separate deploy step.
 *
 *   pnpm worker:bundle
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

const result = await build({
  entryPoints: ["worker/src/index.ts"],
  bundle: true,
  format: "esm",
  target: "es2022",
  platform: "neutral",
  // Workers provide these; bundling them would break the runtime.
  external: ["cloudflare:*", "node:*"],
  minify: true,
  write: false,
  legalComments: "none",
});

const code = result.outputFiles[0].text;

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/worker-bundle.ts",
  `// Generated by scripts/bundle-worker.mjs. Do not edit.\n` +
    `// Source: worker/src/index.ts\n\n` +
    `export const WORKER_SCRIPT = ${JSON.stringify(code)};\n\n` +
    `export const WORKER_BYTES = ${code.length};\n`,
);

console.log(
  `bundled worker: ${(code.length / 1024).toFixed(1)} KB -> src/generated/worker-bundle.ts`,
);
